#!/usr/bin/env python3
"""Generate src/tile_chars.rs from MapTileCharacters in micropolis.h.

Values are obtained by compiling the original enum with g++ and printing it,
so they are exactly what the C++ engine uses.

Usage: tools/gen_tiles.py /path/to/micropolis.h > src/tile_chars.rs
"""
import re, subprocess, sys, tempfile, os

src = open(sys.argv[1]).read()
body = re.search(r'enum MapTileCharacters \{(.*?)\n\};', src, re.S).group(1)
entries = []
for line in body.split('\n'):
    code = re.sub(r'/\*.*?\*/', '', line)
    code = re.sub(r'//.*', '', code).strip()
    for part in filter(None, (p.strip() for p in code.split(','))):
        m = re.match(r'^([A-Za-z_]\w*)\s*(?:=\s*(.+))?$', part)
        if not m:
            sys.exit('unparsed: ' + part)
        entries.append((m.group(1), m.group(2)))

with tempfile.TemporaryDirectory() as d:
    cpp, exe = os.path.join(d, 't.cpp'), os.path.join(d, 't')
    with open(cpp, 'w') as f:
        f.write('#include <cstdio>\nenum MapTileCharacters {\n')
        for n, e in entries:
            f.write(f'  {n}' + (f' = {e}' if e else '') + ',\n')
        f.write('};\nint main(){\n')
        for n, _ in entries:
            f.write(f'  printf("{n} %d\\n",(int){n});\n')
        f.write('}\n')
    subprocess.check_call(['g++', '-o', exe, cpp])
    vals = dict((l.split()[0], int(l.split()[1]))
                for l in subprocess.check_output([exe]).decode().splitlines() if l.strip())

print('//! Tile character constants.\n//!\n//! GENERATED by tools/gen_tiles.py from `MapTileCharacters` in micropolis.h.\n'
      '//! Values come from the C++ compiler. Do not edit manually.\n\n#![allow(dead_code)]\n')
for n, _ in entries:
    v = vals[n]
    print(f'pub const {n}: i32 = {v};' if v < 0 else f'pub const {n}: u16 = {v};')
