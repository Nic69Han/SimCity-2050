//! Golden tests for `traffic.cpp` (`makeTraffic` and its helpers).
//!
//! The expected values come from the ORIGINAL C++ engine, produced by
//! `reference/gold/traffic_gold.cpp` on `assets/cities/haight.cty` (see the
//! comments there). The data below is the harness output; regenerate it
//! with the harness rather than editing it by hand.

use micropolis_core::position::Position;
use micropolis_core::simulation::Simulation;
use micropolis_core::traffic::ZoneType;

const HAIGHT: &[u8] = include_bytes!("../../../assets/cities/haight.cty");

/// Starts from the tile section of the .cty file, as `loadFile` reads it.
/// `doSimInit` is not run: it changes power and status bits, which belong to
/// other modules. The traffic functions only use the file's tile bits.
fn load_raw_tiles(sim: &mut Simulation) {
    assert_eq!(HAIGHT.len(), 27_120);
    let t = &HAIGHT[3120..];
    for i in 0..12_000 {
        sim.tiles[i] = u16::from_be_bytes([t[2 * i], t[2 * i + 1]]);
    }
}

/// FNV-style hash of the tile map, column-major, as in the C++ harness.
fn map_hash(sim: &Simulation) -> u64 {
    let mut h: u64 = 1469598103934665603;
    let (w, hh) = sim.world_size();
    for x in 0..w {
        for y in 0..hh {
            let v = sim.tile(x, y).unwrap();
            h ^= u64::from(v & 0xff);
            h = h.wrapping_mul(1099511628211);
            h ^= u64::from(v >> 8);
            h = h.wrapping_mul(1099511628211);
        }
    }
    h
}

/// Number of tiles with non-zero traffic density, and a hash of the density map.
fn density_stats(sim: &Simulation) -> (i32, u64) {
    let mut h: u64 = 1469598103934665603;
    let mut nz = 0;
    for x in 0..120 {
        for y in 0..100 {
            let v = sim.traffic_density_map.world_get(x, y);
            if v != 0 {
                nz += 1;
            }
            h ^= u64::from(v);
            h = h.wrapping_mul(1099511628211);
        }
    }
    (nz, h)
}

fn zone(v: i32) -> ZoneType {
    match v {
        0 => ZoneType::Commercial,
        1 => ZoneType::Industrial,
        2 => ZoneType::Residential,
        _ => panic!("bad zone {v}"),
    }
}

#[test]
fn raw_city_matches_original_engine() {
    let mut sim = Simulation::with_default_size();
    load_raw_tiles(&mut sim);
    assert_eq!(map_hash(&sim), 0x127c3c57b6ba3a57u64);
}

/// Every entry: variant (0 = `make_traffic`, 1 = `make_traffic_from`,
/// 2 = `make_traffic_at`, which keeps the position stack), start, destination,
/// return value, stack pointer after the call, number of non-zero density
/// tiles, density hash. The density map is cleared before each call, and no
/// heavy-traffic case is included (that path needs the sprite module).
#[test]
fn make_traffic_matches_original_engine() {
    let mut sim = Simulation::with_default_size();
    load_raw_tiles(&mut sim);
    sim.rng.seed(4242);

    let mut connected = 0;
    for (i, &(variant, x, y, dest, ret, sp, nz, hash)) in CASES.iter().enumerate() {
        sim.traffic_density_map.clear();
        sim.traf_max_x = -1;
        sim.traf_max_y = -1;

        let dest = zone(dest);
        let got = match variant {
            0 => sim.make_traffic(x, y, dest),
            1 => sim.make_traffic_from(Position::new(x, y), dest),
            2 => sim.make_traffic_at(x, y, dest),
            _ => unreachable!(),
        };
        let (got_nz, got_hash) = density_stats(&sim);

        assert_eq!(i32::from(got), ret, "case {i}: return value");
        assert_eq!(
            i32::from(sim.cur_map_stack_pointer),
            sp,
            "case {i}: stack pointer"
        );
        assert_eq!(got_nz, nz, "case {i}: non-zero density tiles");
        assert_eq!(got_hash, hash, "case {i}: density map hash");
        assert_eq!(sim.traf_max_x, -1, "case {i}: heavy traffic must not occur");
        if got == 1 {
            connected += 1;
        }
    }
    assert_eq!(connected, 239);
    assert_eq!(
        map_hash(&sim),
        0x127c3c57b6ba3a57u64,
        "traffic must not change tiles"
    );
}

