fn heat_lines(rule: i32, wrap: i32) -> Vec<String> {
    let mut s = Simulation::with_default_size();
    let mut g = Lcg(4242);
    for x in 0..120 {
        for y in 0..100 {
            s.tiles[x * 100 + y] = g.rnd(0, 65535) as u16;
        }
    }
    s.heat_rule = rule;
    s.heat_wrap = wrap;
    s.heat_flow = -7;
    (0..3)
        .map(|step| {
            s.sim_heat();
            format!("{} {}", step, fnv16(s.tiles.iter().copied()))
        })
        .collect()
}

