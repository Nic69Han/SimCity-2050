/// The LCG of `simulate_harness.cpp` (`lcg_next` / `rnd`).
struct Lcg(u32);

impl Lcg {
    fn next(&mut self) -> u32 {
        self.0 = self.0.wrapping_mul(1_103_515_245).wrapping_add(12_345);
        (self.0 >> 8) & 0x00ff_ffff
    }

    /// Inclusive range, as `rnd(lo, hi)` in the harness.
    fn rnd(&mut self, lo: i32, hi: i32) -> i32 {
        lo + (self.next() % ((hi - lo + 1) as u32)) as i32
    }
}

/// `fnv16` of `reference/gold/simulate_harness.cpp` (same as `reference/oracle.cpp`).
fn fnv16(words: impl IntoIterator<Item = u16>) -> u64 {
    let mut h: u64 = 1_469_598_103_934_665_603;
    for w in words {
        h ^= (w & 0xff) as u64;
        h = h.wrapping_mul(1_099_511_628_211);
        h ^= (w >> 8) as u64;
        h = h.wrapping_mul(1_099_511_628_211);
    }
    h
}

fn hash_i16(v: &[i16]) -> u64 {
    fnv16(v.iter().map(|&x| x as u16))
}

fn city_class(v: i32) -> CityClass {
    match v {
        0 => CityClass::Village,
        1 => CityClass::Town,
        2 => CityClass::City,
        3 => CityClass::Capital,
        4 => CityClass::Metropolis,
        _ => CityClass::Megalopolis,
    }
}

fn game_level(v: i32) -> GameLevel {
    GameLevel::from_i16(v as i16).expect("level in 0..=2")
}

/// Compare generated lines with the golden text, line by line.
fn check(section: &str, golden: &str, got: &[String]) {
    let want: Vec<&str> = golden
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .collect();
    assert_eq!(got.len(), want.len(), "{section}: number of cases");
    for (i, (g, w)) in got.iter().zip(want.iter()).enumerate() {
        assert_eq!(g.as_str(), *w, "{section}: case {i}");
    }
}

