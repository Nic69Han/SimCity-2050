fn census_arrays(s: &mut Simulation, g: &mut Lcg) {
    for x in 0..240 {
        s.res_hist[x] = g.rnd(-50, 400) as i16;
        s.com_hist[x] = g.rnd(-50, 400) as i16;
        s.ind_hist[x] = g.rnd(-50, 400) as i16;
        s.crime_hist[x] = g.rnd(0, 255) as i16;
        s.pollution_hist[x] = g.rnd(0, 255) as i16;
        s.money_hist[x] = g.rnd(0, 255) as i16;
    }
}

fn arrays_hashes(s: &Simulation) -> String {
    format!(
        "{} {} {} {} {} {}",
        hash_i16(&s.res_hist),
        hash_i16(&s.com_hist),
        hash_i16(&s.ind_hist),
        hash_i16(&s.crime_hist),
        hash_i16(&s.pollution_hist),
        hash_i16(&s.money_hist)
    )
}

