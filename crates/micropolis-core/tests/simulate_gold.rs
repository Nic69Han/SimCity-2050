#[test]
fn tile_rules_match_original() {
    let mut s = Simulation::with_default_size();
    let (w, h) = s.world_size();
    let mut got = Vec::new();
    // fn: 0 doRoad, 1 doRadTile, 2 doBridge, 3 fireZone, 4 repairZone,
    //     5 drawStadium, 6 coalSmoke, 7 doFire
    for f in 0..8u32 {
        for k in 0..60u32 {
            let seed = 20000 + f * 1000 + k;
            let mut g = Lcg(seed);
            s.rng.seed(seed as i32);

            for x in 0..w {
                for y in 0..h {
                    let mut v = g.rnd(0, 65535) as u16;
                    if f == 7 {
                        v &= !ZONEBIT;
                    }
                    if f == 0 {
                        v |= BURNBIT;
                    }
                    s.tiles[(x * h + y) as usize] = v;
                }
            }
            let px = g.rnd(2, w - 3);
            let py = g.rnd(2, h - 3);
            let pos = Position::new(px, py);
            s.road_effect = g.rnd(0, 32);
            s.road_total = 0;
            s.rail_total = 0;
            let (tw, th) = s.traffic_density_map.size();
            for x in 0..tw {
                for y in 0..th {
                    s.traffic_density_map.set(x, y, g.rnd(0, 255) as u8);
                }
            }
            let (fw, fh) = s.fire_station_effect_map.size();
            for x in 0..fw {
                for y in 0..fh {
                    s.fire_station_effect_map.set(x, y, g.rnd(-5, 150) as i16);
                }
            }
            let (rw, rh) = s.rate_of_growth_map.size();
            for x in 0..rw {
                for y in 0..rh {
                    s.rate_of_growth_map.set(x, y, g.rnd(-200, 200) as i16);
                }
            }

            let mut extra: i64 = 0;
            match f {
                0 => s.do_road(pos),
                1 => s.do_rad_tile(pos),
                2 => {
                    let mut t = BRIDGE_TILES[g.rnd(0, 15) as usize];
                    if g.rnd(0, 3) == 0 {
                        t |= g.rnd(0, 0x3ff) as u16;
                    }
                    let d = if g.rnd(0, 4) == 0 {
                        99999
                    } else {
                        g.rnd(0, 800)
                    };
                    s.tiles[(px * h + py) as usize] = t;
                    let r = s.do_bridge_with_distance(pos, t, d);
                    extra = d as i64 * 2 + r as i64;
                }
                3 => {
                    let mut ch = g.rnd(0, 1023) as u16;
                    if g.rnd(0, 1) != 0 {
                        ch |= ZONEBIT;
                    }
                    s.fire_zone(pos, ch);
                    extra = s.rate_of_growth_map.world_get(px, py) as i64;
                }
                4 => {
                    let zc: u16 = if g.rnd(0, 3) == 0 {
                        g.rnd(0, 1023) as u16
                    } else {
                        ZONE_CENTERS[g.rnd(0, 6) as usize]
                    };
                    let size = if g.rnd(0, 2) == 0 {
                        3
                    } else if g.rnd(0, 1) != 0 {
                        4
                    } else {
                        6
                    };
                    s.repair_zone(pos, zc, size);
                }
                5 => {
                    let st = STADIUM_STATES[g.rnd(0, 1) as usize];
                    s.draw_stadium(pos, st);
                }
                6 => s.coal_smoke(pos),
                _ => s.do_fire(pos),
            }

            got.push(format!(
                "{} {} {} {} {}",
                f,
                fnv16(s.tiles.iter().copied()),
                s.road_total as i32 * 1000 + s.rail_total as i32,
                extra,
                s.rng.random16()
            ));
        }
    }
    check("tiles", TILES, &got);
}

